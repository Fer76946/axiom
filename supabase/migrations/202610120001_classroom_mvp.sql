begin;

-- Preserve the existing profiles/students/grades tables and their rows.
-- Fail rather than silently discard ambiguous legacy data.
do $$
begin
  if exists (select 1 from public.students group by access_code having count(*) > 1) then
    raise exception 'Duplicate student access codes: resolve these before running the MVP migration.';
  end if;
  if exists (select 1 from public.grades group by student_id having count(*) > 1) then
    raise exception 'Multiple overall grades per student: resolve these before running the MVP migration.';
  end if;
  if exists (select 1 from public.students where access_code is null or access_code::text !~ '^[0-9]{7}$') then
    raise exception 'Every existing student must have a valid seven-digit access code.';
  end if;
end $$;

-- The supplied schema has a bigint grades.id. Preserve an existing identity/default.
-- If neither is configured, add automatic IDs without renumbering existing rows.
do $$
declare next_id bigint;
begin
  if exists (
    select 1 from information_schema.columns
    where table_schema = 'public' and table_name = 'grades' and column_name = 'id'
      and data_type = 'bigint' and is_identity = 'NO' and column_default is null
  ) then
    alter table public.grades alter column id add generated by default as identity;
    select greatest(coalesce(max(id), 0) + 1, 1) into next_id from public.grades;
    perform setval(pg_get_serial_sequence('public.grades', 'id'), next_id, false);
  end if;
end $$;
alter table public.grades add column if not exists updated_at timestamptz not null default now();

-- Text preserves leading zeros in newly generated codes.
alter table public.students alter column access_code type text using access_code::text;
alter table public.students alter column access_code set not null;
create unique index if not exists axiom_students_access_code_unique on public.students(access_code);
create unique index if not exists axiom_grades_student_unique on public.grades(student_id);
alter table public.students add constraint axiom_access_code_format check (access_code ~ '^[0-9]{7}$');
alter table public.grades add constraint axiom_overall_grade_range check (grade is null or grade between 0 and 100);

create table public.assessments (
  id uuid primary key default gen_random_uuid(),
  student_id uuid not null references public.students(id) on delete cascade,
  title text not null check (length(trim(title)) between 1 and 120),
  score numeric not null check (score >= 0),
  max_score numeric not null check (max_score > 0),
  date date not null,
  created_at timestamptz not null default now(),
  check (score <= max_score)
);
create index assessments_student_date on public.assessments(student_id, date desc);
create table public.student_sessions (
  token_hash text primary key check (token_hash ~ '^[a-f0-9]{64}$'),
  student_id uuid not null references public.students(id) on delete cascade,
  expires_at timestamptz not null,
  created_at timestamptz not null default now()
);
create index student_sessions_student on public.student_sessions(student_id);
create index student_sessions_expiry on public.student_sessions(expires_at);
create table public.student_login_attempts (
  bucket text primary key,
  window_start timestamptz not null,
  attempts integer not null
);

-- Shared classroom roster: all verified teachers can manage all students,
-- matching the existing app. Per-teacher ownership is a separate product change.
-- Classroom data is accessed only through the role/token-checked functions.
-- Remove existing permissive policies so anon/browser ID edits cannot expose rows.
do $$
declare item record;
begin
  for item in select schemaname, tablename, policyname from pg_policies
    where schemaname = 'public' and tablename in ('students', 'grades', 'assessments', 'student_sessions', 'student_login_attempts', 'profiles')
  loop
    execute format('drop policy %I on %I.%I', item.policyname, item.schemaname, item.tablename);
  end loop;
end $$;
alter table public.students enable row level security;
alter table public.grades enable row level security;
alter table public.assessments enable row level security;
alter table public.student_sessions enable row level security;
alter table public.student_login_attempts enable row level security;
alter table public.profiles enable row level security;
revoke all on public.students, public.grades, public.assessments, public.student_sessions, public.student_login_attempts from anon, authenticated;
revoke all on public.profiles from anon, authenticated;
grant select (id, role) on public.profiles to authenticated;
create policy axiom_read_own_profile on public.profiles for select to authenticated using (id = (select auth.uid()));
grant all on public.students, public.grades, public.assessments, public.student_sessions, public.student_login_attempts, public.profiles to service_role;

-- Atomic rate limit: 30 attempts per address per ten-minute window (shared school networks).
create function public.axiom_allow_student_login(bucket_key text) returns boolean
language plpgsql security definer set search_path = '' as $$
declare total integer;
begin
  delete from public.student_login_attempts where window_start < now() - interval '1 day';
  delete from public.student_sessions where expires_at <= now();
  insert into public.student_login_attempts(bucket, window_start, attempts)
    values (bucket_key, now(), 1)
  on conflict (bucket) do update set
    attempts = case when public.student_login_attempts.window_start <= now() - interval '10 minutes' then 1 else public.student_login_attempts.attempts + 1 end,
    window_start = case when public.student_login_attempts.window_start <= now() - interval '10 minutes' then now() else public.student_login_attempts.window_start end
  returning attempts into total;
  return total <= 30;
end $$;

create function public.axiom_delete_student(target_student_id uuid) returns boolean
language plpgsql security definer set search_path = '' as $$
declare deleted integer;
begin
  delete from public.grades where student_id = target_student_id;
  delete from public.assessments where student_id = target_student_id;
  delete from public.student_sessions where student_id = target_student_id;
  delete from public.students where id = target_student_id;
  get diagnostics deleted = row_count;
  return deleted > 0;
end $$;
revoke all on function public.axiom_allow_student_login(text) from public, anon, authenticated;
revoke all on function public.axiom_delete_student(uuid) from public, anon, authenticated;
grant execute on function public.axiom_allow_student_login(text) to service_role;
grant execute on function public.axiom_delete_student(uuid) to service_role;
commit;
